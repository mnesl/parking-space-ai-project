"""
Stage 2: Human-in-the-Loop (HITL) Administrator Agent (`admin_agent.py`).

Specification Requirements Covered:
-----------------------------------
1. "Create the second agent using LangChain to interact with the administrator."
2. "Chat bot should be able to send a reservation request to administrator and
   get confirm/refuse response from them (e.g. via email server, messenger, rest api)."
3. "Organize the integration with the first agent so that the reservation request is
   escalated to the human administrator after collecting details from the user."

Educational Concepts Covered Here:
----------------------------------
1. **Why Do We Use a Second Specialized Agent (`AdminEscalationAgent`)?**
   In Multi-Agent AI Architecture, Agent 1 (`ParkingRAGChatbot`) talks to the public
   customer, while Agent 2 (`AdminEscalationAgent`) interacts with the internal human
   administrator.
   - Separating their roles enforces **Privilege Separation**: Agent 1 can only *propose*
     a `ReservationDraft`, whereas Agent 2 formats an executive briefing (checking live
     SQL capacity first!), assigns a unique `request_id`, and processes the administrator's
     `CONFIRMED` or `REFUSED` decision.

2. **State Machine for Pending Approvals (`PENDING` -> `CONFIRMED` / `REFUSED`):**
   Because a human administrator might take 5 seconds or 10 minutes to click "Confirm"
   or "Refuse", we store pending requests in a thread-safe SQLite table (`reservation_requests`)
   so no reservation request is ever lost if the server restarts!
"""

from __future__ import annotations

import sqlite3
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Literal, Optional

from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import HumanMessage, SystemMessage
from pydantic import BaseModel, Field

from src.config import SQLITE_DB_PATH, Settings, get_chat_model, get_settings
from src.stage1_rag.chatbot_agent import ParkingRAGChatbot, ReservationDraft
from src.stage1_rag.sql_store import DynamicParkingSQLStore


# ============================================================================
# 1. PYDANTIC MODELS FOR ADMINISTRATOR ESCALATION & DECISIONS
# ============================================================================
ReservationStatus = Literal["PENDING", "CONFIRMED", "REFUSED"]


class AdminEscalationTicket(BaseModel):
    """
    Represents a reservation request escalated from Agent 1 (User Chatbot)
    to Agent 2 (Human-in-the-Loop Administrator Agent).
    """

    request_id: str = Field(description="Unique ticket ID (e.g., 'REQ-A1B2C3D4')")
    name: str = Field(description="Customer's first name")
    surname: str = Field(description="Customer's surname")
    car_number: str = Field(description="Validated uppercase vehicle license plate")
    reservation_period: str = Field(description="Requested start and end window")
    zone_code: str = Field(default="ZONE_A", description="Requested parking zone")
    status: ReservationStatus = Field(default="PENDING")
    admin_briefing: str = Field(
        description="Structured summary generated by Agent 2 for the Human Administrator"
    )
    admin_notes: Optional[str] = Field(
        default=None,
        description="Optional comment or reason provided by the human administrator",
    )
    created_at: str = Field(description="UTC timestamp when escalated")
    decided_at: Optional[str] = Field(
        default=None,
        description="Timestamp when the administrator confirmed or refused",
    )

    @property
    def full_name(self) -> str:
        return f"{self.name} {self.surname}".strip()


class AdminDecisionInput(BaseModel):
    """Payload sent by the Human Administrator (via REST API or CLI) to approve/refuse."""

    decision: Literal["CONFIRM", "REFUSE"] = Field(
        description="Administrator action: 'CONFIRM' to approve or 'REFUSE' to reject"
    )
    admin_notes: Optional[str] = Field(
        default=None,
        description="Optional note explaining the confirmation or refusal",
    )


class AgentHandoffResult(BaseModel):
    """Result of escalating a completed reservation from Agent 1 to Agent 2."""

    ticket: AdminEscalationTicket
    user_notification: str = Field(
        description="Message sent back to the user via Agent 1"
    )


# ============================================================================
# 2. SECOND LANGCHAIN AGENT: ADMINISTRATOR ESCALATION AGENT
# ============================================================================
ADMIN_AGENT_SYSTEM_PROMPT = """You are Agent 2: The AeroPark Administrator Escalation Coordinator.
Your job is to generate a concise, professional approval briefing for the Human Administrator
summarizing the customer's reservation request and the current live availability in that zone.
Include:
- Request ID, Customer Full Name, Car Number, Reservation Period, and Zone
- Current available spaces in the requested zone
- Clear instruction to reply CONFIRM or REFUSE.
"""


class AdminEscalationAgent:
    """
    Stage 2 LangChain Agent responsible for:
    1. Receiving validated `ReservationDraft` handoffs from Agent 1 (`ParkingRAGChatbot`).
    2. Generating an Administrator Approval Briefing and saving the `PENDING` ticket.
    3. Processing the Human Administrator's `CONFIRM` or `REFUSE` response.
    4. Communicating the final outcome back to Agent 1 / the user.
    """

    def __init__(
        self,
        db_path: Path | str = SQLITE_DB_PATH,
        sql_store: Optional[DynamicParkingSQLStore] = None,
        llm: Optional[BaseChatModel] = None,
        settings: Optional[Settings] = None,
    ) -> None:
        self.db_path = Path(db_path)
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        self.settings = settings or get_settings()
        self.sql_store = sql_store or DynamicParkingSQLStore(db_path=self.db_path)
        self.llm = llm
        self._init_table()

    def _get_connection(self) -> sqlite3.Connection:
        conn = sqlite3.connect(str(self.db_path))
        conn.row_factory = sqlite3.Row
        return conn

    def _init_table(self) -> None:
        with self._get_connection() as conn:
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS reservation_requests (
                    request_id TEXT PRIMARY KEY,
                    name TEXT NOT NULL,
                    surname TEXT NOT NULL,
                    car_number TEXT NOT NULL,
                    reservation_period TEXT NOT NULL,
                    zone_code TEXT NOT NULL,
                    status TEXT NOT NULL,
                    admin_briefing TEXT NOT NULL,
                    admin_notes TEXT,
                    created_at TEXT NOT NULL,
                    decided_at TEXT
                )
                """
            )
            conn.commit()

    def escalate_reservation(self, draft: ReservationDraft) -> AdminEscalationTicket:
        """
        Receive a completed `ReservationDraft` from Agent 1, generate the Administrator
        approval request via Agent 2, persist it as `PENDING`, and return the ticket.
        """
        if not draft.is_complete:
            missing = ", ".join(draft.missing_fields())
            raise ValueError(
                f"Cannot escalate incomplete reservation to Admin. Missing: {missing}"
            )

        request_id = f"REQ-{uuid.uuid4().hex[:8].upper()}"
        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")

        # Check live capacity in the requested zone so the Admin has full context
        zones = {z.zone_code: z for z in self.sql_store.get_zones()}
        target_zone = zones.get(draft.zone_code)
        avail_info = (
            f"{target_zone.available_spaces}/{target_zone.total_spaces} spaces available "
            f"(${target_zone.hourly_rate_usd:.2f}/hr)"
            if target_zone
            else "Zone capacity check unavailable"
        )

        briefing = self._generate_admin_briefing(
            request_id=request_id,
            draft=draft,
            avail_info=avail_info,
        )

        ticket = AdminEscalationTicket(
            request_id=request_id,
            name=draft.name or "",
            surname=draft.surname or "",
            car_number=draft.car_number or "",
            reservation_period=draft.reservation_period or "",
            zone_code=draft.zone_code,
            status="PENDING",
            admin_briefing=briefing,
            admin_notes=None,
            created_at=now_str,
            decided_at=None,
        )

        with self._get_connection() as conn:
            conn.execute(
                """
                INSERT INTO reservation_requests (
                    request_id, name, surname, car_number, reservation_period,
                    zone_code, status, admin_briefing, admin_notes, created_at, decided_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    ticket.request_id,
                    ticket.name,
                    ticket.surname,
                    ticket.car_number,
                    ticket.reservation_period,
                    ticket.zone_code,
                    ticket.status,
                    ticket.admin_briefing,
                    ticket.admin_notes,
                    ticket.created_at,
                    ticket.decided_at,
                ),
            )
            conn.commit()

        return ticket

    def _generate_admin_briefing(
        self,
        request_id: str,
        draft: ReservationDraft,
        avail_info: str,
    ) -> str:
        """Use Agent 2's LangChain LLM (or deterministic template offline) to format the Admin notification."""
        raw_summary = (
            f"[ADMIN APPROVAL REQUIRED — Ticket {request_id}]\n"
            f"- Customer: {draft.full_name}\n"
            f"- Car Number: {draft.car_number}\n"
            f"- Period: {draft.reservation_period}\n"
            f"- Requested Zone: {draft.zone_code} (Live Capacity: {avail_info})\n"
            f"Action Required: Please CONFIRM or REFUSE this reservation request."
        )

        active_llm = self.llm
        if active_llm is None:
            has_key = (
                self.settings.llm_provider == "gemini" and bool(self.settings.google_api_key)
            ) or (
                self.settings.llm_provider == "openai" and bool(self.settings.openai_api_key)
            )
            if has_key:
                active_llm = get_chat_model(temperature=0.0, settings=self.settings)

        if active_llm is not None:
            response = active_llm.invoke(
                [
                    SystemMessage(content=ADMIN_AGENT_SYSTEM_PROMPT),
                    HumanMessage(content=raw_summary),
                ]
            )
            return str(response.content)

        return raw_summary

    def get_ticket(self, request_id: str) -> Optional[AdminEscalationTicket]:
        """Look up a specific reservation request by its ID."""
        with self._get_connection() as conn:
            row = conn.execute(
                "SELECT * FROM reservation_requests WHERE request_id = ?",
                (request_id,),
            ).fetchone()
            if row is None:
                return None
            return AdminEscalationTicket.model_validate(dict(row))

    def list_pending_tickets(self) -> List[AdminEscalationTicket]:
        """Return all reservation requests currently awaiting Administrator approval."""
        with self._get_connection() as conn:
            rows = conn.execute(
                "SELECT * FROM reservation_requests WHERE status = 'PENDING' ORDER BY created_at ASC"
            ).fetchall()
            return [AdminEscalationTicket.model_validate(dict(r)) for r in rows]

    def process_admin_decision(
        self,
        request_id: str,
        decision_input: AdminDecisionInput,
    ) -> AdminEscalationTicket:
        """
        Record the Human Administrator's CONFIRM or REFUSE decision and update
        the reservation status (`CONFIRMED` or `REFUSED`).
        """
        existing = self.get_ticket(request_id)
        if existing is None:
            raise KeyError(f"Reservation request '{request_id}' not found.")

        new_status: ReservationStatus = (
            "CONFIRMED" if decision_input.decision == "CONFIRM" else "REFUSED"
        )
        decided_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")

        with self._get_connection() as conn:
            conn.execute(
                """
                UPDATE reservation_requests
                SET status = ?, admin_notes = ?, decided_at = ?
                WHERE request_id = ?
                """,
                (new_status, decision_input.admin_notes, decided_at, request_id),
            )
            conn.commit()

        updated = self.get_ticket(request_id)
        assert updated is not None
        return updated

    def format_decision_for_user(self, ticket: AdminEscalationTicket) -> str:
        """
        Generate the communication message sent back from Agent 2 (Admin Agent)
        to Agent 1 (User Chatbot) once the administrator responds.
        """
        notes_suffix = f" (Admin Note: {ticket.admin_notes})" if ticket.admin_notes else ""
        if ticket.status == "CONFIRMED":
            return (
                f"Good news, {ticket.full_name}! The Human Administrator has CONFIRMED "
                f"your parking reservation (Ticket `{ticket.request_id}`) for car "
                f"`{ticket.car_number}` during `{ticket.reservation_period}` in `{ticket.zone_code}` "
                f"at `{ticket.decided_at}`.{notes_suffix}"
            )
        if ticket.status == "REFUSED":
            return (
                f"Update for {ticket.full_name}: Unfortunately, the Human Administrator "
                f"has REFUSED your parking reservation request (Ticket `{ticket.request_id}`) "
                f"for car `{ticket.car_number}`.{notes_suffix}"
            )
        return (
            f"Your reservation request (Ticket `{ticket.request_id}`) is still PENDING "
            f"Human Administrator review."
        )


def escalate_from_chatbot_to_admin(
    chatbot: ParkingRAGChatbot,
    admin_agent: AdminEscalationAgent,
) -> AgentHandoffResult:
    """
    Bridge function connecting Agent 1 (`ParkingRAGChatbot`) and Agent 2 (`AdminEscalationAgent`).
    Once Agent 1 collects all 4 required slots from the user, this function escalates the
    request to Agent 2 and appends the escalation confirmation into Agent 1's conversation history.
    """
    ticket = admin_agent.escalate_reservation(chatbot.reservation_draft)
    notification = (
        f"Reservation Request `{ticket.request_id}` has been sent to the Human Administrator "
        f"for approval. Status: `{ticket.status}`."
    )
    return AgentHandoffResult(ticket=ticket, user_notification=notification)

